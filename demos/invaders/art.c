const iv_sprite_t *iv_glyph (char c)
{
	static iv_sprite_t g[sizeof glyphs / sizeof glyphs[0]];
	for (unsigned i = 0; i < sizeof glyphs / sizeof glyphs[0]; i++)
	{
		if (glyphs[i].c == c)
		{
			g[i].w = 5;
			g[i].h = 7;
			g[i].rows = glyphs[i].rows;
			return &g[i];
		}
	}
	return NULL;
}
