const iv_sprite_t *iv_glyph (char c)
{
	static iv_sprite_t g;
	const char *rows = arcade_glyph (c);
	if (!rows)
	{
		return NULL;
	}
	g.w = 5;
	g.h = 7;
	g.rows = rows;
	return &g;
}
